"""The stylesheet behind the `extended` profile's colouring and tables.

`render_css()` is the one source: `./manage.py build_highlight_css` writes it to
`core/css/highlight.css` (committed, loaded by `core/base.html`) and a test fails while the
committed file differs. Pygments' `xcode` style for light and `github-dark` for dark, both scoped
to `pre.hl` and using the `hl-` class prefix. The block background is the Sage scheme's gray-50 /
gray-900 variable (so it follows the colour scheme and high contrast), and every token colour is
checked against that colour's Sage value and raised to 4.5:1 where it falls short.
"""

import re

from pygments.formatters.html import HtmlFormatter

from apps.core.color_schemes import DEFAULT, GRAY_STEPS, get_scheme

from .highlight import HIGHLIGHT_PREFIX

CSS_PATH = 'core/css/highlight.css'
#: Pygments styles: the light one passes `MIN_CONTRAST` on its own, the dark one is nudged where a
#: token falls short (`_readable`).
LIGHT_STYLE = 'xcode'
DARK_STYLE = 'github-dark'
#: WCAG AA for text, what `test_color_schemes.py` holds every text pair of the site to.
MIN_CONTRAST = 4.5

_HEADER = (
    '/* Generated by `./manage.py build_highlight_css` from apps/core/markdown/highlight_css.py.\n'
    '   Do not edit by hand. */\n'
)

_TABLES = """.md-table {
  overflow-x: auto;
}
.md-table th,
.md-table td {
  padding: 0.375rem 0.75rem;
  border: 1px solid rgb(var(--c-gray-200));
}
.dark .md-table th,
.dark .md-table td {
  border-color: rgb(var(--c-gray-700));
}
"""


def _normalise(color: str) -> str:
    """`abc` / `aabbcc` (no `#`) as lower-case six digits."""
    color = color.lower()
    return ''.join(c * 2 for c in color) if len(color) == 3 else color


def _luminance(color: str) -> float:
    channels = [int(color[i : i + 2], 16) / 255 for i in (0, 2, 4)]
    linear = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def contrast(a: str, b: str) -> float:
    """WCAG contrast ratio of two six-digit hex colours (no `#`)."""
    lighter, darker = sorted((_luminance(a), _luminance(b)), reverse=True)
    return (lighter + 0.05) / (darker + 0.05)


def _readable(color: str, background: str, extreme: str) -> str:
    """`color`, moved towards `extreme` (black on light, white on dark) in 5% steps until it
    reaches `MIN_CONTRAST` on `background`; unchanged when it already does."""
    color = _normalise(color)
    for step in range(21):
        mixed = ''.join(
            f'{round(int(color[i : i + 2], 16) * (1 - step / 20) + int(extreme[i : i + 2], 16) * step / 20):02x}'
            for i in (0, 2, 4)
        )
        if contrast(mixed, background) >= MIN_CONTRAST:
            return mixed
    return extreme


_COLOR = re.compile(r'(?<![-\w])color:\s*#([0-9a-fA-F]{3,6})\b')
_TOKEN_BACKGROUND = re.compile(r'background-color:\s*#([0-9a-fA-F]{3,6})\b')


def _fix_line(line: str, background: str, extreme: str) -> str:
    """Make the text colour of one rule readable on the rule's own background if it has one, else
    on the block's."""
    own = _TOKEN_BACKGROUND.search(line)
    bg = _normalise(own.group(1)) if own else background
    return _COLOR.sub(lambda m: f'color: #{_readable(m.group(1), bg, extreme)}', line)


def _style(style: str, scope: str, *, background: str, extreme: str, block: str) -> str:
    """Pygments' token rules for `style`, only those that apply inside `scope`, with every text
    colour raised to `MIN_CONTRAST` on `background` (the hex of the colour `block` paints).

    Dropped: the unscoped rules Pygments also writes (`pre { line-height }`, the line-number
    columns: they would change every `<pre>` on the site), the `.hll` line highlight (`hl_lines` is
    never set) and Pygments' own block rule, replaced by `block` (the scheme's variables).
    """
    rules = HtmlFormatter(style=style, classprefix=HIGHLIGHT_PREFIX).get_style_defs(scope)
    kept = [
        _fix_line(line, background, extreme)
        for line in rules.splitlines()
        if line.startswith(scope) and not line.startswith(f'{scope} {{') and '.hll' not in line
    ]
    return '\n'.join([f'{scope} {{ {block} }}', *kept])


def render_css() -> str:
    sage = get_scheme(DEFAULT)
    gray = dict(zip(GRAY_STEPS, sage.gray))
    light = _style(
        LIGHT_STYLE,
        'pre.hl',
        background=_normalise(gray[50].lstrip('#')),
        extreme='000000',
        block='background: rgb(var(--c-gray-50)); color: rgb(var(--c-gray-900));',
    )
    dark = _style(
        DARK_STYLE,
        '.dark pre.hl',
        background=_normalise(gray[900].lstrip('#')),
        extreme='ffffff',
        block='background: rgb(var(--c-gray-900)); color: rgb(var(--c-gray-50));',
    )
    return (
        f'{_HEADER}\n/* Light: Pygments "{LIGHT_STYLE}". */\n{light}\n\n'
        f'/* Dark: Pygments "{DARK_STYLE}". */\n{dark}\n\n'
        f'/* Tables of the extended profile. */\n{_TABLES}'
    )
