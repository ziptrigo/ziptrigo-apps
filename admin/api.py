#!python
"""
Generate the API spec, `docs/openapi.yml` (OpenAPI 3.1).

The spec is read from the backend (`config/api.py`). Its version, `info.version`, lives in
`config/api_version.py` and is raised only when the spec changed since the committed file.
"""

import copy
import json
import os
import re
from enum import Enum
from pathlib import Path
from typing import Annotated, Any

import typer

from . import PROJECT_ROOT
from .utils import logger

app = typer.Typer(
    help=__doc__,
    no_args_is_help=True,
    add_completion=False,
    rich_markup_mode='markdown',
)

SPEC_PATH = PROJECT_ROOT / 'docs' / 'openapi.yml'
VERSION_PATH = PROJECT_ROOT / 'config' / 'api_version.py'

HEADER = (
    '# Generated by `inv api generate` from the backend (config/api.py). Do not edit by hand.\n'
    '# The version is config/api_version.py; see CLAUDE.md, "OpenAPI document".\n'
)

_VERSION_LINE = re.compile(r"^API_VERSION = '([^']*)'$", re.MULTILINE)
_SEMVER = re.compile(r'(\d+)\.(\d+)\.(\d+)')


class Bump(str, Enum):
    """Which part of the version a changed spec raises."""

    PATCH = 'patch'
    MINOR = 'minor'
    MAJOR = 'major'


def _resolve_lazy(value):
    """
    Recursively force lazy translation proxies to plain strings, and tuples to lists.

    Django validators wrap their text in `gettext_lazy`, producing
    `django.utils.functional.Promise` instances rather than `str`, which neither `json` nor
    `yaml.safe_dump` can serialize; `safe_dump` refuses tuples as well.
    """
    from django.utils.functional import Promise

    if isinstance(value, Promise):
        return str(value)
    if isinstance(value, dict):
        return {key: _resolve_lazy(item) for key, item in value.items()}
    if isinstance(value, list | tuple):
        return [_resolve_lazy(item) for item in value]
    return value


def setup_django():
    """Configure Django settings."""
    import django
    from django.apps import apps

    os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'config.settings')

    if not apps.ready:
        django.setup()


def build_spec() -> dict[str, Any]:
    """The backend's spec, as plain JSON-compatible data."""
    setup_django()

    from config.api import api

    spec = _resolve_lazy(api.get_openapi_schema())
    # A JSON round trip leaves only plain types (and fails loudly on anything else).
    return json.loads(json.dumps(spec))


def strip_version(spec: dict[str, Any]) -> dict[str, Any]:
    """A copy of the spec without `info.version`: what "the spec changed" is judged on."""
    stripped = copy.deepcopy(spec)
    stripped.get('info', {}).pop('version', None)
    return stripped


def bump_version(version: str, part: Bump) -> str:
    """Raise one part of a `major.minor.patch` version, resetting the parts after it."""
    match = _SEMVER.fullmatch(version)
    if not match:
        raise ValueError(f'Not a major.minor.patch version: {version!r}')
    major, minor, patch = (int(group) for group in match.groups())
    if part == Bump.MAJOR:
        return f'{major + 1}.0.0'
    if part == Bump.MINOR:
        return f'{major}.{minor + 1}.0'
    return f'{major}.{minor}.{patch + 1}'


def with_version(spec: dict[str, Any], version: str) -> dict[str, Any]:
    """A copy of the spec whose `info.version` is `version`."""
    versioned = copy.deepcopy(spec)
    versioned.setdefault('info', {})['version'] = version
    return versioned


def render_yaml(spec: dict[str, Any]) -> str:
    """The file's text. Keys keep Ninja's order and long lines are never wrapped, so a change to
    the API is a small diff."""
    import yaml

    body = yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=1_000_000)
    return HEADER + body


def read_spec(path: Path) -> dict[str, Any] | None:
    """The committed spec, or `None` when there is no file yet."""
    import yaml

    if not path.exists():
        return None
    return yaml.safe_load(path.read_text(encoding='utf-8'))


def read_version_constant(path: Path) -> str:
    """The version in `config/api_version.py`."""
    matches = _VERSION_LINE.findall(path.read_text(encoding='utf-8'))
    if len(matches) != 1:
        raise ValueError(f"Expected one line `API_VERSION = '...'` in {path}")
    return matches[0]


def write_version_constant(path: Path, version: str) -> None:
    """Rewrite the `API_VERSION = '...'` line of `config/api_version.py`."""
    read_version_constant(path)  # Exactly one such line, or an error.
    text = path.read_text(encoding='utf-8')
    path.write_text(_VERSION_LINE.sub(f"API_VERSION = '{version}'", text), encoding='utf-8')


def plan_generation(
    new_spec: dict[str, Any],
    committed_spec: dict[str, Any] | None,
    current_version: str,
    bump: Bump,
) -> tuple[str, bool]:
    """`(version, changed)`: the version the file should have and whether anything must be
    written. The first file keeps the current version; an unchanged spec writes nothing."""
    if committed_spec is None:
        return current_version, True
    committed_version = committed_spec.get('info', {}).get('version')
    if strip_version(new_spec) == strip_version(committed_spec):
        # Same spec. Only a file whose version disagrees with the constant needs rewriting.
        return current_version, committed_version != current_version
    return bump_version(current_version, bump), True


def is_current(
    new_spec: dict[str, Any], committed_spec: dict[str, Any] | None, current_version: str
) -> bool:
    """Whether the committed file is the backend's spec at the current version."""
    if committed_spec is None:
        return False
    return (
        strip_version(new_spec) == strip_version(committed_spec)
        and committed_spec.get('info', {}).get('version') == current_version
    )


def _relative(path: Path) -> str:
    try:
        return str(path.relative_to(PROJECT_ROOT))
    except ValueError:
        return str(path)


@app.command(name='generate')
def generate(
    bump: Annotated[
        Bump,
        typer.Option(
            help='Part of the version to raise when the spec changed: `major` for a breaking '
            'change, `patch` for wording only.',
            case_sensitive=False,
        ),
    ] = Bump.MINOR,
    check: Annotated[
        bool,
        typer.Option(
            '--check',
            help='Write nothing; exit 1 if `docs/openapi.yml` is out of date.',
            show_default=False,
        ),
    ] = False,
):
    """
    Generate `docs/openapi.yml` from the backend.

    Writes the file (and raises the version in `config/api_version.py`) only when the spec
    changed since the committed file; otherwise it changes nothing.
    """
    spec_path, version_path = SPEC_PATH, VERSION_PATH
    try:
        new_spec = build_spec()
        committed = read_spec(spec_path)
        current_version = read_version_constant(version_path)
    except Exception as e:
        logger.error(f'Failed to read the API spec: {e}')
        raise typer.Exit(1)

    if check:
        if is_current(new_spec, committed, current_version):
            logger.info(f'{_relative(spec_path)} is up to date ({current_version}).')
            return
        logger.error(f'{_relative(spec_path)} is out of date: run `inv api generate`.')
        raise typer.Exit(1)

    version, changed = plan_generation(new_spec, committed, current_version, bump)
    if not changed:
        logger.info(f'{_relative(spec_path)} is up to date ({version}).')
        return

    spec_path.parent.mkdir(parents=True, exist_ok=True)
    spec_path.write_text(render_yaml(with_version(new_spec, version)), encoding='utf-8')
    if version != current_version:
        write_version_constant(version_path, version)
    if committed is None:
        logger.info(f'{_relative(spec_path)} written ({version}).')
    else:
        previous = committed.get('info', {}).get('version', '?')
        logger.info(f'{_relative(spec_path)}: {previous} -> {version}')


if __name__ == '__main__':
    app()
